import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import path from 'node:path';
const root=path.resolve(import.meta.dirname,'..');
const html=fs.readFileSync(path.join(root,'guia/index.html'),'utf8');
const data=JSON.parse(fs.readFileSync(path.join(root,'data/research.json'),'utf8'));
assert(!/\{\{[A-Z_]+\}\}/.test(html),'Unfilled template');
const script=html.match(/<script>([\s\S]*?)<\/script>/)[1];
new vm.Script(script);
const embedded=JSON.parse(script.match(/const DATA=([^\n]+);/)[1]);
assert.deepEqual(embedded,data,'Embedded data differs from source');
const ids=[...html.matchAll(/\bid="([^"]+)"/g)].map(x=>x[1]);
assert.equal(new Set(ids).size,ids.length,'Duplicate IDs');
for(const [,id] of html.matchAll(/href="#([^"]+)"/g))assert(ids.includes(id),'Missing anchor '+id);
for(const [,asset] of html.matchAll(/(?:src|href)="((?:assets\/|\.\.\/data\/)[^"]+)"/g))assert(fs.existsSync(path.resolve(root,'guia',asset)),'Missing asset '+asset);
const func=script.match(/function estimate\(m,s\)\{[^\n]+/)[0];
const context=vm.createContext({});vm.runInContext(func,context);
const estimate=(m,s)=>context.estimate(m,s);
const s={requests:10000,inputTokens:2000,outputTokens:500,cacheRead:0,cacheWrite:0,tier:1};
assert.equal(estimate(data.models[0],s),4.5);
assert.equal(estimate(data.models[1],s),90);
assert.equal(estimate(data.models[0],{...s,cacheRead:100}),2.7);
assert.equal(estimate(data.models[0],{...s,cacheWrite:100}),5);
assert.equal(estimate(data.models[0],{...s,tier:.5}),2.25);
const short=estimate(data.models[1],{...s,requests:1,inputTokens:272000,outputTokens:1000});
const long=estimate(data.models[1],{...s,requests:1,inputTokens:272001,outputTokens:1000});
assert.equal(short,.554);assert(Math.abs(long-1.103004)<1e-10);
for(const b of data.benchmarks)for(const r of b.rows)assert(r[1]>=0&&r[1]<=100);
console.log('PASS: JSON consistency, JS syntax, anchors/assets, pricing, cache, tier, long-context boundary, benchmark ranges.');
await import('./verify-i18n.mjs');
